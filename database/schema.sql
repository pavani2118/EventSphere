-- EventSphere bootstrap schema for a fresh PostgreSQL database.
--
-- This file is intentionally additive and must only be run against a fresh
-- database. It does not drop objects, delete rows, or alter an existing
-- database. The waitlist idempotency migration is incorporated below so a
-- fresh database reaches the same end state without rerunning the migration.
--
-- Evidence sources:
--   app/**/*.py, app/agents/**/*.py, database/migrations/001_waitlist_idempotency.sql
--
-- All application identifiers are BIGINT because the waitlist migration
-- explicitly requires bookings.waitlist_id BIGINT. Times are timestamptz
-- because the application uses timezone-aware datetime values.

BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'ATTENDEE',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT users_role_check
        CHECK (role IN ('ATTENDEE', 'ADMIN', 'ORGANISER', 'GATE_STAFF'))
);

CREATE UNIQUE INDEX users_email_unique
    ON users (email);

CREATE TABLE user_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT user_sessions_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX user_sessions_token_hash_unique
    ON user_sessions (token_hash);

CREATE INDEX user_sessions_user_id_idx
    ON user_sessions (user_id);

CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    location TEXT NOT NULL,
    capacity INTEGER NOT NULL,
    description TEXT,
    image_path TEXT,
    hourly_rate NUMERIC(12, 2) NOT NULL DEFAULT 0,
    private_hire_available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT venues_capacity_check CHECK (capacity > 0),
    CONSTRAINT venues_hourly_rate_check CHECK (hourly_rate >= 0)
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    category VARCHAR(100) NOT NULL,
    venue_id BIGINT NOT NULL,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT events_time_order_check
        CHECK (end_time > start_time),
    CONSTRAINT events_status_check
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED')),
    CONSTRAINT events_venue_id_fkey
        FOREIGN KEY (venue_id) REFERENCES venues(id),
    CONSTRAINT events_created_by_fkey
        FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE INDEX events_status_idx
    ON events (status);

CREATE INDEX events_venue_time_idx
    ON events (venue_id, start_time, end_time);

CREATE TABLE ticket_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    category_name VARCHAR(100) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT ticket_categories_price_check CHECK (price >= 0),
    CONSTRAINT ticket_categories_quantity_check CHECK (quantity > 0),
    CONSTRAINT ticket_categories_event_id_fkey
        FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
);

CREATE INDEX ticket_categories_event_id_idx
    ON ticket_categories (event_id);

CREATE TABLE waitlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT waitlist_quantity_check CHECK (quantity BETWEEN 1 AND 10),
    CONSTRAINT waitlist_status_check
        CHECK (
            status IN (
                'WAITING', 'OFFERED', 'ACCEPTED', 'FULFILLED',
                'EXPIRED', 'CANCELLED'
            )
        ),
    CONSTRAINT waitlist_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT waitlist_event_id_fkey
        FOREIGN KEY (event_id) REFERENCES events(id)
);

CREATE INDEX idx_waitlist_event
    ON waitlist (event_id);

CREATE INDEX waitlist_fifo_idx
    ON waitlist (event_id, status, created_at, id);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    waitlist_id BIGINT,
    total_amount NUMERIC(12, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT bookings_quantity_check CHECK (quantity > 0),
    CONSTRAINT bookings_status_check
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT bookings_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT bookings_event_id_fkey
        FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT bookings_waitlist_id_fkey
        FOREIGN KEY (waitlist_id) REFERENCES waitlist(id)
);

CREATE INDEX bookings_user_id_idx
    ON bookings (user_id);

CREATE INDEX bookings_event_id_idx
    ON bookings (event_id);

CREATE UNIQUE INDEX bookings_waitlist_id_unique
    ON bookings (waitlist_id)
    WHERE waitlist_id IS NOT NULL;

CREATE UNIQUE INDEX waitlist_active_user_event_unique
    ON waitlist (user_id, event_id)
    WHERE status = 'WAITING';

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    payment_reference TEXT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    paid_at TIMESTAMPTZ,
    CONSTRAINT payments_amount_check CHECK (amount >= 0),
    CONSTRAINT payments_status_check
        CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED')),
    CONSTRAINT payments_booking_id_fkey
        FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE
);

CREATE INDEX payments_booking_id_idx
    ON payments (booking_id);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    qr_token TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'VALID',
    checked_in_at TIMESTAMPTZ,
    checked_in_by BIGINT,
    CONSTRAINT tickets_status_check
        CHECK (status IN ('VALID', 'USED', 'CANCELLED')),
    CONSTRAINT tickets_booking_id_fkey
        FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE,
    CONSTRAINT tickets_category_id_fkey
        FOREIGN KEY (category_id) REFERENCES ticket_categories(id),
    CONSTRAINT tickets_checked_in_by_fkey
        FOREIGN KEY (checked_in_by) REFERENCES users(id)
);

CREATE INDEX tickets_booking_id_idx
    ON tickets (booking_id);

CREATE INDEX tickets_category_id_idx
    ON tickets (category_id);

CREATE INDEX tickets_qr_token_idx
    ON tickets (qr_token);

CREATE TABLE venue_hire_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    venue_id BIGINT NOT NULL,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    purpose VARCHAR(250) NOT NULL,
    guest_count INTEGER NOT NULL,
    quoted_price NUMERIC(12, 2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'CONFIRMED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT venue_hire_time_order_check
        CHECK (end_time > start_time),
    CONSTRAINT venue_hire_guest_count_check
        CHECK (guest_count BETWEEN 1 AND 10000),
    CONSTRAINT venue_hire_quoted_price_check CHECK (quoted_price >= 0),
    CONSTRAINT venue_hire_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT venue_hire_venue_id_fkey
        FOREIGN KEY (venue_id) REFERENCES venues(id)
);

CREATE INDEX venue_hire_venue_time_idx
    ON venue_hire_requests (venue_id, start_time, end_time);

CREATE INDEX venue_hire_user_id_idx
    ON venue_hire_requests (user_id);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT notifications_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX notifications_user_created_idx
    ON notifications (user_id, created_at DESC);

CREATE TABLE agent_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender TEXT NOT NULL,
    receiver TEXT NOT NULL,
    performative VARCHAR(20) NOT NULL,
    content JSONB NOT NULL DEFAULT '{}'::JSONB,
    conversation_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT agent_messages_performative_check
        CHECK (
            performative IN (
                'REQUEST', 'AGREE', 'REFUSE', 'PROPOSE', 'INFORM', 'FAILURE'
            )
        )
);

CREATE INDEX agent_messages_created_idx
    ON agent_messages (created_at DESC);

CREATE INDEX agent_messages_conversation_idx
    ON agent_messages (conversation_id);

CREATE TABLE agent_states (
    agent_name TEXT PRIMARY KEY,
    state JSONB NOT NULL DEFAULT '{}'::JSONB,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMIT;
